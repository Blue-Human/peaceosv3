#!/usr/bin/env node
// Copies ONLY what core needs to resolve org_identity (keys/<org_id>/<key_id>.pub)
// from the transparency/registry git submodule into a generated TS module that
// Vite inlines into the portal bundle at build time. No manifest, timestamps or
// docs from the registry are embedded. Regenerate by re-running this script
// (wired into `pnpm dev` / `pnpm build`, see web/package.json).
import { execFileSync } from 'node:child_process';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webRoot = join(scriptDir, '..');
const repoRoot = join(webRoot, '..');
export const REGISTRY_ROOT = join(repoRoot, 'transparency', 'registry');
export const OUTPUT_PATH = join(webRoot, 'src', 'embeddedRegistry.generated.ts');

const KEY_REF_PATTERN = /^keys\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+\.pub$/;

/**
 * Only `keys/<org_id>/<key_id>.pub` refs are accepted — the exact shape
 * core's checkOrgIdentity() looks up. Anything else in the registry
 * (manifest, timestamps, docs, revocations) is intentionally left out.
 */
export async function collectRegistryKeyFiles(registryRoot) {
  const keysDir = join(registryRoot, 'keys');
  const files = [];

  async function walk(dir) {
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch (err) {
      if (err.code === 'ENOENT') return;
      throw err;
    }
    for (const entry of entries) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(path);
        continue;
      }
      if (!entry.isFile() || !entry.name.endsWith('.pub')) continue;

      const ref = relative(registryRoot, path).replaceAll('\\', '/');
      if (!KEY_REF_PATTERN.test(ref)) {
        throw new Error(`Refusing to embed unexpected registry ref: "${ref}"`);
      }
      files.push({ ref, bytes: await readFile(path) });
    }
  }

  await walk(keysDir);
  files.sort((a, b) => a.ref.localeCompare(b.ref));
  return files;
}

export function readRegistryVersion(registryRoot) {
  try {
    const commit = execFileSync('git', ['-C', registryRoot, 'rev-parse', '--short', 'HEAD'], {
      encoding: 'utf8',
    }).trim();
    const date = execFileSync('git', ['-C', registryRoot, 'log', '-1', '--format=%cI'], {
      encoding: 'utf8',
    }).trim();
    return { commit, date };
  } catch (err) {
    throw new Error(
      `Could not read the transparency registry submodule at "${registryRoot}". ` +
        'Run `git submodule update --init transparency/registry` and try again.\n' +
        String(err.message ?? err),
    );
  }
}

export function generateEmbeddedRegistryModule(version, files) {
  const entries = files
    .map(({ ref, bytes }) => `  ${JSON.stringify(ref)}: ${JSON.stringify(bytes.toString('base64'))},`)
    .join('\n');

  return `// AUTO-GENERATED by web/scripts/build-embedded-registry.mjs — do not edit by hand.
// Snapshot of transparency/registry (commit ${version.commit}, ${version.date}).
// Regenerate with \`pnpm --filter @peaceos/web run generate:registry\` after
// updating the submodule (see web/README.md).

export interface EmbeddedRegistryVersion {
  commit: string;
  date: string;
}

export const EMBEDDED_REGISTRY_VERSION: EmbeddedRegistryVersion = ${JSON.stringify(version, null, 2)};

export const EMBEDDED_REGISTRY_FILES: Record<string, string> = {
${entries}
};
`;
}

async function main() {
  const version = readRegistryVersion(REGISTRY_ROOT);
  const files = await collectRegistryKeyFiles(REGISTRY_ROOT);
  if (files.length === 0) {
    throw new Error(`No "keys/<org_id>/<key_id>.pub" files found under "${REGISTRY_ROOT}".`);
  }
  const contents = generateEmbeddedRegistryModule(version, files);
  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, contents, 'utf8');
  console.log(`Embedded ${files.length} registry key(s) from commit ${version.commit} (${version.date}).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message ?? err);
    process.exitCode = 1;
  });
}
